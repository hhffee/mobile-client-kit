import shutil
import subprocess
import sys
import tempfile

ROOT = Path(__file__).resolve().parents[1]
CORE = "submodules/TelegramCore/Sources/"
PEER = "submodules/TelegramUI/Components/PeerInfo/PeerInfoScreen/Sources/"
PATHS = [
    "submodules/TelegramUI/Sources/AppDelegate.swift", "submodules/PasscodeCore/Sources/Passcode.swift",
    "submodules/TelegramUI/Sources/ChatControllerNode.swift",
    "build-system/Make/Make.py", "docs/state-sync.md", "Telegram/BUILD",
    "Telegram/Telegram-iOS/Telegram.icon/icon.json",
    CORE + "State/ManagedAccountPresence.swift",
    CORE + "State/ManagedLocalInputActivities.swift",
    CORE + "State/SynchronizePeerReadState.swift",
    CORE + "State/ManagedSynchronizeConsumeMessageContentsOperations.swift",
    CORE + "State/ManagedConsumePersonalMessagesActions.swift",
    CORE + "State/AccountViewTracker.swift",
    CORE + "State/Sync/StateReplay+Messages.swift",
    CORE + "State/Sync/UpdateInterpreter+Messages.swift",
    CORE + "State/ServerMessageMerge.swift",
    CORE + "State/ManagedAutoremoveMessageOperations.swift",
    CORE + "ApiUtils/StoreMessage_Telegram.swift",
    CORE + "Account/AccountManager.swift",
    CORE + "SyncCore/SyncCore_StandaloneAccountTransaction.swift",
    "submodules/TelegramUI/Components/Chat/ChatMessageDateAndStatusNode/Sources/StringForMessageTimestampStatus.swift",
    CORE + "TelegramEngine/Messages/ApplyMaxReadIndexInteractively.swift",
    CORE + "TelegramEngine/Messages/MarkAllChatsAsRead.swift",
    CORE + "TelegramEngine/Messages/ReplyThreadHistory.swift",
    CORE + "TelegramEngine/Messages/AdMessages.swift",
    PEER + "PeerInfoScreen.swift", PEER + "PeerInfoSettingsItems.swift", PEER + "PeerInfoScreenSettingsActions.swift",
]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("--refresh-local", action="store_true", help="Replace only files generated by this overlay in the local checkout")
    args = parser.parse_args()
    source = args.source.resolve()
    lock = json.loads((ROOT / "upstream.lock.json").read_text())
    head = subprocess.check_output(["git", "-C", source, "rev-parse", "HEAD"], text=True).strip()
    if head != lock["commit"]:
        raise SystemExit("Upstream revision mismatch")
    git_dir = subprocess.check_output(["git", "-C", source, "rev-parse", "--absolute-git-dir"], text=True).strip()
    with tempfile.TemporaryDirectory(prefix="ayu-overlay-") as temporary:
        snapshot = Path(temporary)
        for path in PATHS:
            contents = subprocess.check_output(["git", "-C", source, "show", f"HEAD:{path}"])
            destination = snapshot / path
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(contents)
        # prepare.py only reads HEAD from Git. All reads/writes of source files target
        # this independent temporary snapshot; no Git/index mutation is performed.
        env = dict(os.environ, GIT_DIR=git_dir, GIT_WORK_TREE=str(snapshot))
        command = [sys.executable, ROOT / "scripts/prepare.py", snapshot, "--unsigned"]
        subprocess.run([str(arg) for arg in command], env=env, check=True)
        second = subprocess.run([str(arg) for arg in command], env=env, capture_output=True, text=True)
        if second.returncode == 0 or "Overlay already applied" not in second.stderr:
            raise SystemExit("Repeated application was not rejected")
        if args.refresh_local:
            for path in snapshot.rglob("*"):
                if path.is_file():
                    target = source / path.relative_to(snapshot)
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(path, target)
            # Remove the obsolete allowlist change from an early local overlay revision.
            allowlist = source / "submodules/Postbox/AllowedImporters.txt"
            if allowlist.exists():
                text = allowlist.read_text(encoding="utf-8")
                text = text.replace(CORE + "AyuHistoryBridge.swift\n", "")
                allowlist.write_text(text, encoding="utf-8", newline="\n")
        print("PASS: clean pinned snapshots accept all integration edits; repeat application is rejected.")


if __name__ == "__main__":
    main()

